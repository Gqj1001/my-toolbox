  /* 全半角、空白归一化后的索引（提高命中率） */
  function norm(s) {
    return String(s == null ? '' : s)
      .replace(/[\uFF01-\uFF5E]/g, ch => String.fromCharCode(ch.charCodeAt(0) - 0xFEE0)) // 全角→半角
      .replace(/\u3000/g, ' ')
      .replace(/[（]/g, '(').replace(/[）]/g, ')')
      // "（型）""（含参）""（2）"这类插入语：去掉后更容易命中主干
      // 例如「求余弦（型）函数的最小正周期」→「求余弦函数的最小正周期」
      .replace(/\((?:型|含参|不含参|2|1|Ⅰ|Ⅱ|I|II)\)/g, '')
      .replace(/\s+/g, '')
      .trim();
  }
  const NORM = Object.create(null);
